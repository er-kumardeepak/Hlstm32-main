uint16_t Modbus_CRC16(uint8_t *buffer, uint16_t len) {
    uint16_t crc = 0xFFFF;
    for (uint16_t pos = 0; pos < len; pos++) {
        crc ^= (uint16_t)buffer[pos];
        for (int i = 8; i != 0; i--) {
            if ((crc & 0x0001) != 0) {
                crc >>= 1;
                crc ^= 0xA001;
            } else {
                crc >>= 1;
            }
        }
    }
    return crc;
}

// EM4M is Big Endian (ABCD) -> convert to STM32 (DCBA)
float EM4M_BytesToFloat(uint8_t *data) {
    float val;
    uint8_t *val_ptr = (uint8_t*)&val;
    val_ptr[0] = data[3]; // LSB
    val_ptr[1] = data[2];
    val_ptr[2] = data[1];
    val_ptr[3] = data[0]; // MSB
    return val;
}

// EM2M is Swapped (CDAB) -> convert to STM32 (DCBA)
float EM2M_BytesToFloat(uint8_t *data) {
    float val;
    uint8_t *val_ptr = (uint8_t*)&val;
    val_ptr[0] = data[1]; // D
    val_ptr[1] = data[0]; // C
    val_ptr[2] = data[3]; // B
    val_ptr[3] = data[2]; // A
    return val;
}

// Function to poll the EM2M Meter
uint8_t Read_EM2M(UART_HandleTypeDef *huart, uint8_t slave_id, uint16_t reg_addr, float *out_value) {
    uint8_t request[8] = {slave_id, 0x04, (reg_addr >> 8) & 0xFF, reg_addr & 0xFF, 0x00, 0x02, 0, 0};
    uint16_t crc = Modbus_CRC16(request, 6);
    request[6] = crc & 0xFF; request[7] = (crc >> 8) & 0xFF;

    if (HAL_UART_Transmit(huart, request, 8, 100) != HAL_OK) return 0;
    uint8_t response[9];
    if (HAL_UART_Receive(huart, response, 9, 200) != HAL_OK) return 0;

    uint16_t rx_crc = (response[8] << 8) | response[7];
    if (Modbus_CRC16(response, 7) != rx_crc) return 0;

    *out_value = EM2M_BytesToFloat(&response[3]);
    return 1;
}

// Function to poll the EM4M Meter
